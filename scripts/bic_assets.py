"""Generate/check browser BIC assets. Refresh uses only the Python standard library."""
import argparse
import csv
import hashlib
import io
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from tempfile import TemporaryDirectory

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from twpay_bic import (  # noqa: E402
    CSV_URL, BicUpdateError, read_bic_map, stdlib_http_get, update_bic_dataset,
)

CSV_PATH = "data/BIC.csv"
JS_PATH = "docs/js/bic-data.js"
MANIFEST_PATH = "docs/data/bic-manifest.json"
ASSET_PATHS = (CSV_PATH, JS_PATH, MANIFEST_PATH)
MIN_RECORDS = 50


def validate_change(previous, current):
    if len(current) < MIN_RECORDS:
        raise BicUpdateError(f"BIC 筆數不得少於 {MIN_RECORDS}")
    removed = previous.keys() - current.keys()
    if len(removed) > max(2, len(previous) // 10):
        raise BicUpdateError("BIC 移除超過 10%（至少允許 2 筆），請人工調查來源")


def csv_bytes(mapping):
    output = io.StringIO(newline="")
    writer = csv.writer(output, lineterminator="\n")
    writer.writerow(("BIC", "Name"))
    writer.writerows(sorted(mapping.items()))
    return output.getvalue().encode("utf-8")


def js_bytes(mapping):
    # ASCII JSON escapes also prevent a source name from injecting JS or HTML.
    rows = [{"bic": bic, "name": name} for bic, name in sorted(mapping.items())]
    return (
        "// Generated by scripts/bic_assets.py from data/BIC.csv; do not edit.\n"
        "const BIC_LIST = " + json.dumps(rows, ensure_ascii=True, indent=2) + ";\n"
    ).encode("utf-8")


def make_manifest(mapping, updated_at):
    parsed = datetime.fromisoformat(updated_at.replace("Z", "+00:00"))
    if parsed.tzinfo is None:
        raise ValueError("updated_at must include a timezone")
    return {
        "schema_version": 1,
        "source": CSV_URL,
        "sha256": hashlib.sha256(csv_bytes(mapping)).hexdigest(),
        "record_count": len(mapping),
        "updated_at": updated_at,
    }


def assets(mapping, updated_at):
    manifest = make_manifest(mapping, updated_at)
    return {
        CSV_PATH: csv_bytes(mapping),
        JS_PATH: js_bytes(mapping),
        MANIFEST_PATH: (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode(),
    }


def existing_timestamp(root, mapping):
    path = root / MANIFEST_PATH
    if path.exists():
        manifest = json.loads(path.read_text(encoding="utf-8"))
        timestamp = manifest["updated_at"]
        if manifest == make_manifest(mapping, timestamp):
            return timestamp
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def describe_change(previous, current):
    # JSON quotes untrusted names; never interpret source text as shell/Markdown.
    return json.dumps({
        "added": {k: current[k] for k in sorted(current.keys() - previous.keys())},
        "removed": {k: previous[k] for k in sorted(previous.keys() - current.keys())},
        "renamed": {
            k: {"before": previous[k], "after": current[k]}
            for k in sorted(previous.keys() & current.keys()) if previous[k] != current[k]
        },
    }, ensure_ascii=True, indent=2)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--refresh", action="store_true")
    parser.add_argument("--bundle", type=Path, help="Write only the three generated assets here")
    args = parser.parse_args()
    if args.bundle and not args.refresh:
        parser.error("--bundle requires --refresh")
    try:
        previous = read_bic_map(ROOT / CSV_PATH)
        current = previous
        if args.refresh:
            with TemporaryDirectory() as directory:
                current = update_bic_dataset(stdlib_http_get, Path(directory) / "BIC.csv")
            validate_change(previous, current)
            print(describe_change(previous, current))
        else:
            validate_change(previous, current)
        expected = assets(current, existing_timestamp(ROOT, current))
        if args.check:
            for name, content in expected.items():
                if not (ROOT / name).is_file() or (ROOT / name).read_bytes() != content:
                    raise BicUpdateError(f"{name} 已過期，請執行 python scripts/bic_assets.py")
            print("BIC assets and manifest verified")
        else:
            destination = args.bundle or ROOT
            for name, content in expected.items():
                path = destination / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content)
    except (BicUpdateError, ValueError, KeyError, OSError) as exc:
        parser.error(str(exc))


if __name__ == "__main__":
    main()
